package schema

import (
	_ "embed"
	"encoding/json"
	"fmt"
	"reflect"
	"sort"

	"github.com/RubenRibGarcia/asyncgo/internal/mappingconfig"
	"github.com/RubenRibGarcia/asyncgo/spec"
)

// maxAliasDepth bounds how many `type X Y` hops mappingFor follows. Go rejects
// a cycle among defined types at compile time, so the guard only defends against
// an alias table built by hand — cheap insurance against an infinite loop in a
// hot derivation path.
const maxAliasDepth = 32

// builtinMappings is the built-in mapping table: third-party types asyncgo
// derives correctly with no project configuration. It is data, not code, so
// shipping a mapping never adds a dependency on the library it describes — every
// entry is a name that is only looked up when derivation meets that exact type.
//
//go:embed builtin_mappings.yaml
var builtinMappings []byte

var (
	// mappingRegistry maps a fully-qualified type name (pkgPath.TypeName) to the
	// schema that overrides derivation for that type. Populated by
	// MapSchema/MapSchemaByName (built-ins, user init, generated harness main) and
	// read by FromType. Not safe for concurrent use, matching registry in
	// registry.go: registration finishes before derivation starts.
	mappingRegistry = map[string]*spec.Schema{}

	// aliasRegistry maps a derived alias's fully-qualified name to the name of
	// the type it was declared from (`pkg.OrderID` -> `github.com/gofrs/uuid.UUID`).
	// Reflection cannot walk that link, so the discovery pass emits an edge per
	// `type X Y` declaration and the harness records it with MapAlias.
	aliasRegistry = map[string]string{}

	// consulted records every fully-qualified name that resolved through
	// mappingRegistry, so MappingWarnings can report the rest.
	consulted = map[string]bool{}

	// builtins records which keys came from the embedded table. They are excluded
	// from MappingWarnings: they are always registered, and most modules use none
	// of them.
	builtins = map[string]bool{}
)

// init registers the exact-type special cases as built-in mappings. time.Time is
// the reference example as well as a special case: it is a struct whose fields
// are all unexported, so without a mapping it would derive as an empty object.
func init() { registerBuiltins() }

// registerBuiltins fills the registry with the built-in tier: the exact-type
// special cases first, then the embedded third-party table. It is a function
// rather than the body of init so a test can restore the registry to its
// post-init state without re-running package initialization.
func registerBuiltins() {
	registerMapping("time.Time", &spec.Schema{Type: "string", Format: "date-time"}, true)
	loadBuiltinMappings()
}

// MapSchema registers the schema fn returns as the derivation override for T.
// T must be a named type: the mapping is keyed by its fully-qualified name, so an
// anonymous type has no key. fn is called once, here, rather than lazily at every
// use site — the purity contract makes laziness pointless, and the eager call
// surfaces a panicking function with the registration on the stack.
//
// A mapping outranks both spec.SchemaProvider and kind-based derivation: the
// document's author is overriding the type's suggested default. Registering a
// second mapping for the same type replaces the first.
//
// This is the Go-API entry point for types the project does not own; a
// third-party type is named by its import path, so nothing about the type itself
// has to change. asyncgo.yaml covers the same ground declaratively.
func MapSchema[T any](fn func() *spec.Schema) {
	t := deref(reflect.TypeFor[T]())
	name := Name(t)
	if name == "" {
		panic("schema.MapSchema: " + t.String() +
			" has no fully-qualified name; a mapping is keyed by pkgPath.TypeName")
	}
	MapSchemaByName(name, fn())
}

// MapSchemaByName registers s as the derivation override for the type named by
// its fully-qualified name (pkgPath.TypeName).
//
// Name-keying is what lets a project map a type it cannot add a method to. It
// also means a typo registers a mapping that never matches anything: use
// MappingWarnings — or the asyncgo CLI, which reports warnings — to catch it. A
// nil s is a programmer error and panics.
func MapSchemaByName(fqn string, s *spec.Schema) {
	registerMapping(fqn, s, false)
}

// MapAlias records that aliasFQN is a type declared as baseFQN (`type OrderID
// uuid.UUID` -> OrderID, github.com/gofrs/uuid.UUID). Discovery emits one edge per
// such declaration; derivation follows the chain when the alias has no exact
// mapping and no provider of its own.
//
// It is generated by the harness and is not intended to be called by hand. An
// empty or self-referential edge is ignored rather than reported: it cannot
// resolve to a mapping, and a mapping that never applies is already warned about.
func MapAlias(aliasFQN, baseFQN string) {
	if aliasFQN == "" || baseFQN == "" || aliasFQN == baseFQN {
		return
	}
	aliasRegistry[aliasFQN] = baseFQN
}

// MapSchemaJSON registers the schema encoded as JSON as the derivation override
// for the type named by its fully-qualified name. It is the form asyncgo.yaml
// takes: the harness embeds the validated payload verbatim, and this call checks
// it decodes into a spec.Schema before it is used.
func MapSchemaJSON(fqn, payload string) error {
	return registerJSONMapping(fqn, payload, false)
}

// MappingWarnings returns the sorted fully-qualified names of the user-declared
// mappings — config and API alike — that derivation never consulted.
//
// Name-keyed registration fails silently by nature: the type may be third-party
// and absent from the module, so "does this type exist" cannot be checked
// before the harness runs. Consultation is the only reliable catch, and the
// result is a warning rather than an error because an unused mapping is
// legitimate in a module that declares more than one document's worth of them.
// Built-in mappings never warn: they are always registered and usually unused.
func MappingWarnings() []string {
	var out []string
	for fqn := range mappingRegistry {
		if builtins[fqn] || consulted[fqn] {
			continue
		}
		out = append(out, fqn)
	}
	sort.Strings(out)
	return out
}

// registerMapping is the single write path for mappingRegistry, so the built-in
// bookkeeping cannot drift between the three callers.
func registerMapping(fqn string, s *spec.Schema, builtin bool) {
	if s == nil {
		panic("schema: mapping for " + fqn + " is nil")
	}
	mappingRegistry[fqn] = s
	// Re-registration replaces (last wins), including a built-in: a project that
	// overrides time.Time or a third-party entry takes ownership of the name.
	if builtin {
		builtins[fqn] = true
		return
	}
	delete(builtins, fqn)
}

// registerJSONMapping decodes a JSON Schema Object and registers it. Both the
// public JSON entry point and the embedded built-in loader go through here, so a
// malformed payload is one error path rather than two.
func registerJSONMapping(fqn, payload string, builtin bool) error {
	var s spec.Schema
	if err := json.Unmarshal([]byte(payload), &s); err != nil {
		return fmt.Errorf("mapping %s: %w", fqn, err)
	}
	registerMapping(fqn, &s, builtin)
	return nil
}

// loadBuiltinMappings parses the embedded table through the same whitelist parser
// a project's asyncgo.yaml uses. A failure is a build-time bug (the table is
// compiled in and covered by tests), so it panics at init rather than silently
// deriving every third-party type by kind.
func loadBuiltinMappings() {
	cfg, err := mappingconfig.Parse(builtinMappings)
	if err != nil {
		panic("schema: built-in mappings: " + err.Error())
	}
	for _, m := range cfg.Mappings {
		if err := registerJSONMapping(m.FQN, m.Schema, true); err != nil {
			panic("schema: built-in mappings: " + err.Error())
		}
	}
}

// exactMapping returns a copy of the mapping registered for t's own
// fully-qualified name, or nil when t has none. It is the highest-precedence tier
// of derivation: an exact mapping outranks a provider.
func exactMapping(t reflect.Type) *spec.Schema {
	t = deref(t)
	if !isNamed(t) {
		return nil
	}
	fqn := Name(t)
	s, ok := mappingRegistry[fqn]
	if !ok {
		return nil
	}
	consulted[fqn] = true
	return cloneSchema(s)
}

// mappingFor resolves the mapping that applies to t — an exact mapping for t's
// own name, or one inherited through the alias chain — and returns a copy, or nil
// when t is unmapped at every step. The resolved name is marked consulted.
//
// It runs below the provider tier, so a type with its own provider keeps it: an
// inherited mapping is implicit, while a provider is a schema the author wrote for
// that exact type.
func mappingFor(t reflect.Type) *spec.Schema {
	t = deref(t)
	if !isNamed(t) {
		return nil
	}
	fqn := Name(t)
	for range maxAliasDepth {
		if s, ok := mappingRegistry[fqn]; ok {
			consulted[fqn] = true
			return cloneSchema(s)
		}
		base, ok := aliasRegistry[fqn]
		if !ok {
			return nil
		}
		fqn = base
	}
	return nil
}

// cloneSchema deep-copies s so a use site cannot mutate the registered schema and
// every consultation returns an independent node.
//
// The copy is a JSON round-trip rather than a field-by-field literal: spec.Schema
// is a flat data struct whose every field already carries a JSON tag, so the
// round-trip cannot silently miss a field a later release adds, and it rebuilds
// the nested pointers, slices and maps that sharing would alias. A schema that
// JSON cannot encode (an enum holding a channel, say) is returned as-is: the
// alternative is dropping the author's mapping.
func cloneSchema(s *spec.Schema) *spec.Schema {
	if s == nil {
		return nil
	}
	raw, err := json.Marshal(s)
	if err != nil {
		return s
	}
	var out spec.Schema
	if err := json.Unmarshal(raw, &out); err != nil {
		return s
	}
	return &out
}
